// Imperium Gzowianskie: opens the game in headless Chrome with the family code and checks that the Octopus connects, speaks and that a voice tool call moves the game.
import { createRequire } from 'node:module'
const require = createRequire('/Users/jurek/openclaw/node_modules/')
const { chromium } = require('playwright-core')
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
const errors = []
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
page.on('pageerror', e => errors.push('pageerror ' + e.message))
await page.goto(process.env.URL || 'http://localhost:8465/', { waitUntil: 'load' })
await page.evaluate(() => localStorage.clear())
await page.reload({ waitUntil: 'load' })
await page.fill('#code', process.argv[2] || 'gzowo')
await page.click('#start')
await page.waitForSelector('#go', { timeout: 30000 })
const pausedAtStart = await page.evaluate(() => !!document.querySelector('#pause'))
await page.evaluate(() => { window.__talk = 0; new MutationObserver(() => { if (document.querySelector('#octo').classList.contains('talk')) window.__talk++ }).observe(document.querySelector('#octo'), { attributes: true }) })
await page.click('#go')
await page.waitForTimeout(9000)
const afterTurn = await page.evaluate(() => ({ line: document.querySelector('#line').textContent, talk: window.__talk, mic: !document.querySelector('#mic').hidden, off: document.querySelector('#octo').classList.contains('off') }))
const tool = await page.evaluate(() => window.__game.tool('rzuc_kostkami', {}))
await page.waitForTimeout(1500)
const afterTool = await page.evaluate(() => { const S = window.__game.state(); return { rolled: S.rolled, pos: S.players[0].pos, pending: S.pending && S.pending.type } })
await page.dispatchEvent('#mic', 'pointerdown', { pointerId: 1 })
await page.waitForTimeout(1200)
await page.dispatchEvent('#mic', 'pointerup', { pointerId: 1 })
await page.waitForTimeout(2500)
const micOk = await page.evaluate(() => document.querySelector('#mic').textContent)
console.log(JSON.stringify({ pausedAtStart, afterTurn, tool, afterTool, micLabelAfter: micOk, errors }, null, 1))
await browser.close()
process.exit(errors.length || !afterTurn.talk ? 1 : 0)
